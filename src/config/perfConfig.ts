/**
 * 性能开关（作者实测核显占用偏高时用）。
 *
 * 背景：主题里有多处 backdrop-filter（毛玻璃），它会让元素**强制生成合成层**，
 * 滚动/动画时每帧都要重新合成 —— 把模糊半径调成 0 也**不会**移除这个图层，
 * 必须直接去掉 backdrop-filter 属性才有效。所以这里给一个总开关。
 *
 * 低配模式做的事：去掉全部毛玻璃 + 停掉装饰性无限循环动画（旋转/脉冲/回落箭头等）。
 * 视觉上会少一点"玻璃感"，换来明显更低的 GPU 占用。
 *
 * 改完到管理面板「发布」页推送即可生效。
 */

type PerfConfig = {
	/** 低配模式总开关 */
	lowSpec: boolean;
};

export const perfConfig: PerfConfig = {
	lowSpec: true,
};
